SYSTEM = """Ты извлекаешь данные из текста бизнес-документа (счёт, коммерческое предложение, акт).
Ответ — ТОЛЬКО один JSON-объект, без пояснений и без markdown. Все ключи обязательны:

{
  "doc_type": "invoice | commercial_offer | act | unknown",
  "supplier_name": строка или null,
  "supplier_bin": строка из ровно 12 цифр или null,
  "doc_number": строка или null,
  "doc_date": "YYYY-MM-DD" или null,
  "currency": "KZT" | "USD" | "EUR" | null,
  "total_amount": число или null,
  "vat_amount": число или null,
  "line_items": [{"name": строка, "qty": число или null, "price": число или null}],
  "field_confidence": {"<имя поля>": число от 0 до 1},
  "warnings": [строки]
}

ЖЁСТКИЕ ПРАВИЛА
1. Если значения нет в тексте — null. Ничего не выдумывай и не вычисляй:
   не выводи БИН из названия, не подставляй сегодняшнюю дату, не считай НДС сам, если сумма НДС не написана.
2. supplier — это тот, кто выставляет документ (поставщик/исполнитель/продавец), а не заказчик/покупатель.
   Если у поставщика нет БИН, а есть только БИН покупателя — supplier_bin = null.
   «НДС не облагается», «без НДС» — это vat_amount = null, а не 0.
   Если название поставщика двуязычное (казахское / русское) — верни русскую форму одним названием.
3. Числа — JSON-числа (186180, а не "186 180"). Сумма прописью допустима (рус. и каз.).
4. total_amount — итоговая сумма к оплате (с НДС, если он указан).
5. Если в тексте две разные даты выдачи или два разных «итого» — выбери первое по тексту
   и добавь предупреждение в warnings. Дата «действительно до …» — не дата документа.
6. Текст может содержать OCR-ошибки (буква О вместо 0, l вместо 1) — исправляй их в числах
   и добавляй предупреждение.
"""


def build_messages(text: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": f"<document>\n{text}\n</document>"},
    ]


def repair_message(errors: str) -> dict:
    return {
        "role": "user",
        "content": "Твой ответ не прошёл автоматическую проверку:\n" + errors +
                   "\nВерни исправленный JSON целиком, по той же схеме, без пояснений.",
    }
